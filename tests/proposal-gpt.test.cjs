const assert=require('node:assert/strict');
const GPT=require('../proposal-gpt.js');
const calc={product:'OptiMaxx Educación',input:{monthly:3500,years:18},result:{fund:1000000},savedAt:'2026-10-16'};
const fields=Object.fromEntries(Object.keys(GPT.limits).map(k=>[k,'Pendiente de confirmar con el asesor']));
const c=GPT.context(calc), reply={version:1,caseId:c.caseId,product:c.product,fields};
const initial=JSON.stringify(calc);
assert.deepEqual(GPT.parse(JSON.stringify(reply),calc),fields);
assert.deepEqual(GPT.parse('```json\n'+JSON.stringify(reply)+'\n```',calc),fields);
assert(GPT.prompt(calc).includes('3500'));assert(GPT.prompt(calc).includes(c.caseId));
assert.throws(()=>GPT.parse(JSON.stringify(reply),{...calc,input:{monthly:4000}}),/otro cálculo/);
assert.throws(()=>GPT.parse(JSON.stringify({...reply,product:'OptiMaxx Plus'}),calc),/otro cálculo/);
for(const invalid of ['texto','null','[]','{}'])assert.throws(()=>GPT.parse(invalid,calc));
for(const value of [null,[],{},23,''])assert.throws(()=>GPT.parse(JSON.stringify({...reply,fields:{...fields,objective:value}}),calc));
assert.throws(()=>GPT.parse(JSON.stringify({...reply,fields:{...fields,result:12}}),calc));
assert.throws(()=>GPT.parse(JSON.stringify({...reply,result:12}),calc));
assert.throws(()=>GPT.parse(JSON.stringify({...reply,fields:{...fields,strategy:'x'.repeat(501)}}),calc),/demasiado largo/);
assert.throws(()=>GPT.prompt(null),/Guarda primero/);assert.throws(()=>GPT.parse('{}',null),/Guarda primero/);
assert.equal(JSON.stringify(calc),initial);
console.log('PASS: prompt, structured import, field lengths, missing and invalid input, wrong product/scenario, immutable calculation.');
